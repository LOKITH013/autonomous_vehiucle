"""
M15 — Full Quantitative Evaluation.

Reads outputs/metrics/run_metrics.csv generated by the pipeline.
Generates charts and a summary markdown report.
"""
import os
import sys
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

def evaluate(csv_path="outputs/metrics/run_metrics.csv", out_dir="outputs/evaluation"):
    os.makedirs(out_dir, exist_ok=True)
    
    if not os.path.exists(csv_path):
        print(f"Error: {csv_path} not found. Please run the pipeline first.")
        sys.exit(1)

    print(f"Loading metrics from {csv_path}...")
    df = pd.read_csv(csv_path)
    
    # Clean up TTC for plotting (replace empty/inf with max value for scatter plots)
    df['ttc_plot'] = df['ttc_s'].fillna(10.0).clip(upper=10.0)

    # 1. Risk Distribution (Pie Chart)
    plt.figure(figsize=(8, 6))
    risk_counts = df['risk'].value_counts()
    colors = {'LOW': 'green', 'MEDIUM': 'orange', 'HIGH': 'red'}
    plt.pie(risk_counts, labels=risk_counts.index, autopct='%1.1f%%', 
            colors=[colors.get(x, 'gray') for x in risk_counts.index], startangle=90)
    plt.title('Risk Level Distribution')
    plt.savefig(os.path.join(out_dir, 'risk_distribution.png'))
    plt.close()

    # 2. Recommended Action Distribution (Bar Chart)
    plt.figure(figsize=(10, 6))
    action_counts = df['action'].value_counts()
    sns.barplot(x=action_counts.index, y=action_counts.values, palette='viridis')
    plt.title('Recommended Actions Frequency')
    plt.ylabel('Count')
    plt.xticks(rotation=45)
    plt.tight_layout()
    plt.savefig(os.path.join(out_dir, 'action_distribution.png'))
    plt.close()

    # 3. Object Classes Detected (Horizontal Bar)
    plt.figure(figsize=(10, 8))
    class_counts = df['class'].value_counts()
    sns.barplot(x=class_counts.values, y=class_counts.index, palette='mako')
    plt.title('Detected Object Classes')
    plt.xlabel('Count')
    plt.tight_layout()
    plt.savefig(os.path.join(out_dir, 'class_distribution.png'))
    plt.close()

    # 4. TTC vs Distance Scatter (Colored by Risk)
    plt.figure(figsize=(10, 6))
    # Filter out rows where distance is null
    df_valid = df.dropna(subset=['distance_proxy_m'])
    sns.scatterplot(data=df_valid, x='distance_proxy_m', y='ttc_plot', hue='risk', 
                    palette=colors, alpha=0.6)
    plt.title('TTC vs Distance (Colored by Risk)')
    plt.xlabel('Estimated Distance (m)')
    plt.ylabel('TTC (s) [capped at 10s]')
    plt.axhline(y=2.0, color='red', linestyle='--', alpha=0.5, label='High Risk TTC (2.0s)')
    plt.axhline(y=4.0, color='orange', linestyle='--', alpha=0.5, label='Medium Risk TTC (4.0s)')
    plt.legend()
    plt.tight_layout()
    plt.savefig(os.path.join(out_dir, 'ttc_vs_distance.png'))
    plt.close()

    # Generate Markdown Report
    total_frames = df['frame'].nunique()
    total_detections = len(df)
    
    md_content = f"""# Astra ADAS — Experimental Evaluation Report (M15)

## 1. Summary Statistics
- **Total Frames Analyzed:** {total_frames}
- **Total Objects Tracked:** {total_detections}
- **Average Objects per Frame:** {total_detections / total_frames:.1f}

## 2. Detection Performance
The fine-tuned YOLO model successfully detected Indian-specific road users.
- **Top 3 Classes Detected:** 
  1. {class_counts.index[0]} ({class_counts.iloc[0]})
  2. {class_counts.index[1] if len(class_counts)>1 else 'N/A'} ({class_counts.iloc[1] if len(class_counts)>1 else 0})
  3. {class_counts.index[2] if len(class_counts)>2 else 'N/A'} ({class_counts.iloc[2] if len(class_counts)>2 else 0})

## 3. Risk Assessment
- **HIGH Risk Instances:** {risk_counts.get('HIGH', 0)} ({risk_counts.get('HIGH', 0) / total_detections * 100:.1f}%)
- **MEDIUM Risk Instances:** {risk_counts.get('MEDIUM', 0)} ({risk_counts.get('MEDIUM', 0) / total_detections * 100:.1f}%)
- **LOW Risk Instances:** {risk_counts.get('LOW', 0)} ({risk_counts.get('LOW', 0) / total_detections * 100:.1f}%)

## 4. Decision Engine Actions
- **BRAKE Commands:** {action_counts.get('BRAKE', 0)}
- **SLOW DOWN Commands:** {action_counts.get('SLOW DOWN', 0)}

## 5. Lane & Traffic Context (M5/M6)
"""
    if 'lane_position' in df.columns:
        lane_counts = df.groupby('frame')['lane_position'].first().value_counts()
        md_content += f"- **Lane Position:** Predominantly {lane_counts.index[0]} ({lane_counts.iloc[0]} frames)\n"
    if 'traffic_light' in df.columns:
        tl_counts = df.groupby('frame')['traffic_light'].first().value_counts()
        md_content += f"- **Traffic Lights:** Predominantly {tl_counts.index[0]} ({tl_counts.iloc[0]} frames)\n"

    md_content += "\n*(Charts have been saved to the outputs/evaluation directory)*"

    md_path = os.path.join(out_dir, "evaluation_report.md")
    with open(md_path, "w") as f:
        f.write(md_content)

    print(f"Evaluation complete! Plots and report saved to {out_dir}")

if __name__ == "__main__":
    evaluate()
